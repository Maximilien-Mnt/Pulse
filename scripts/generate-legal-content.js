/**
 * Generates lib/legalContent.ts from the markdown files in /legal.
 *
 * This avoids needing a custom Metro transformer for .md files. The
 * generated TypeScript module exports each legal document's raw markdown
 * as a string constant, which Metro bundles natively.
 *
 * Run: node scripts/generate-legal-content.js
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const legalDir = path.join(root, "legal");
const outFile = path.join(root, "lib", "legalContent.ts");

const files = [
  { key: "terms", file: "01-conditions-utilisation.md" },
  { key: "privacy", file: "02-politique-confidentialite.md" },
  { key: "bugReport", file: "03-signaler-un-bug.md" },
  { key: "moderation", file: "04-politique-de-moderation.md" },
  { key: "imprint", file: "05-mentions-legales.md" },
];

function escapeTemplateLiteral(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const lines = [
  "// ---------------------------------------------------------------------------",
  "// AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.",
  "//",
  "// Generated by scripts/generate-legal-content.js from the markdown",
  "// files in /legal. Re-run `node scripts/generate-legal-content.js`",
  "// after editing any legal document.",
  "// ---------------------------------------------------------------------------",
  "",
  "export const LEGAL_CONTENT = {",
];

for (const { key, file } of files) {
  const content = fs.readFileSync(path.join(legalDir, file), "utf8");
  lines.push(`  ${key}: \`${escapeTemplateLiteral(content)}\`,`);
}

lines.push("} as const;");
lines.push("");
lines.push("export type LegalContentKey = keyof typeof LEGAL_CONTENT;");
lines.push("");

fs.writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Generated ${path.relative(root, outFile)}`);